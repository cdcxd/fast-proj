#!/usr/bin/env bash
# Regenerate the self-contained bench candidate utm.js with the current
# build/simd.wasm inlined as base64. Used by the perf protocol runs
# (node + bun workers and the Chromium page, which cannot read node builtins).
set -euo pipefail
cd "$(dirname "$0")/.."
node --input-type=module - <<'EOF'
import { readFileSync, writeFileSync } from 'node:fs';
const bytes = readFileSync('build/simd.wasm');
const b64 = Buffer.from(bytes).toString('base64');
const src = `// GENERATED by scripts/embed-artifact.sh — do not edit.
// Self-contained wasm-backed candidate for bench/compare-performance.mjs.
// Works in both node workers and the Chromium browser leg (served at
// /candidate/utm.js, where only same-directory imports resolve): the simd
// artifact is inlined as base64 and the converter core has no node deps.
// No TypeScript fallback here - this is a bench artifact; the shipping
// wrapper (wasm-utm.mjs) keeps the fallback path.
import { createConverter } from './wasm-utm-core.mjs';

const ARTIFACT_BASE64 =
  '${b64}';

const bytes = Uint8Array.from(atob(ARTIFACT_BASE64), (c) => c.charCodeAt(0));
const { instance } = await WebAssembly.instantiate(bytes, {});
const e = instance.exports;
const cache = new Map();

export function utm({ zone, south = false, ellipsoid }) {
  const key = zone + '/' + (south ? 1 : 0) + '/' + (ellipsoid ? ellipsoid.a + ':' + ellipsoid.f : 'wgs84');
  let c = cache.get(key);
  if (!c) {
    c = createConverter(e, { zone, south, ellipsoid });
    cache.set(key, c);
  }
  return c;
}
`;
writeFileSync('utm.js', src);
console.log('wrote utm.js', src.length, 'bytes (artifact', bytes.length, 'bytes)');
EOF
